/* Public correspondence: profanity, source safety and authorization regressions.
 * No database calls or external credentials needed for these pure checks.
 */
'use strict';
const assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url');
const path=require('node:path'),fs=require('node:fs');
(async()=>{
 const backend=await import(pathToFileURL(path.resolve(__dirname,'../correspondence-worker/worker.mjs')).href);
 const {screenedText,allowedOrigin,publicationStatus}=backend;
 assert.equal(publicationStatus('public'),'approved','public letters must post instantly after safety checks');
 assert.equal(publicationStatus('editor'),'pending','private editorial correspondence waits in the inbox');
 assert.equal(screenedText('A splendid book from Charlotte Brontë.').offensive,false);
 assert.equal(screenedText('Ash Wednesday is a notable poem.').offensive,false);
 assert.equal(screenedText('The narration of Jane Eyre needs attention.').offensive,false);
 assert.equal(screenedText('This is sh!t.').offensive,true);
 assert.equal(screenedText('What the f.u.c.k').offensive,true);
 assert.equal(screenedText('Scunthorpe is an English town.').offensive,false);
 assert.equal(screenedText('Dickens and Charlotte Brontë are remarkable.').offensive,false);
 assert.equal(screenedText('Thank you for your letter.').links,false);
 assert.equal(screenedText('visit https://example.com').links,true);
 assert.equal(screenedText('<script>alert(1)</script>').markup,true);
 assert.equal(allowedOrigin('https://opheliasopenbooks.github.io'),true);
 assert.equal(allowedOrigin('https://opheliasopenbooks.github.io.evil.example'),false);
 assert.equal(allowedOrigin('http://opheliasopenbooks.github.io'),false);
 assert.equal(allowedOrigin('https://untrusted.example'),false);
 const html=fs.readFileSync(path.resolve(__dirname,'../correspondence.html'),'utf8');
 const editor=fs.readFileSync(path.resolve(__dirname,'../editor-desk.html'),'utf8');
 const inbox=fs.readFileSync(path.resolve(__dirname,'../editors-inbox.html'),'utf8');
 const config=fs.readFileSync(path.resolve(__dirname,'../public/correspondence-config.js'),'utf8');
 const frontend=fs.readFileSync(path.resolve(__dirname,'../public/js/ophelia-correspondence.js'),'utf8');
 assert.match(html,/data-correspondence="public"/);
 assert.ok(html.includes('Share a Favorite Quotation'));
 assert.ok(html.includes('name="quote_text"'));
 assert.ok(html.includes('name="quote_book"'));
 assert.ok(html.includes('data-letter-filter="quotation"'));
 const front=fs.readFileSync(path.resolve(__dirname,'../public/js/ophelia-correspondence.js'),'utf8');
 assert.ok(front.includes("if(widget!==null)form.querySelector('[data-send]').disabled=false"));
 assert.ok(front.includes("el('blockquote','quote-card',letter.quote_text)"));
 assert.ok(front.includes("result.status==='approved'?'Your letter is published!"),'public confirmation reflects immediate publication');
 assert.ok(front.includes("adminView='inbox'"),'editor views do not require checking all public posts');
 assert.ok(front.includes("['hide','delete']"),'editor can hide and remove already published posts');
 assert.ok(inbox.includes('Recent public posts'),'editor may review public posts without pre-approving them');
 assert.ok(html.includes('appear as soon as you post'),'board promises immediate publication');
 const schema=fs.readFileSync(path.resolve(__dirname,"../correspondence-worker/schema.sql"),"utf8");
 assert.ok(schema.includes("quote_text TEXT NOT NULL"));
 assert.ok(schema.includes("letter_type TEXT NOT NULL"));
 assert.match(editor,/data-correspondence="editor"/);
 assert.match(inbox,/data-correspondence="inbox"/);
 assert.ok(config.includes('apiBase:""'),'messages stay disabled until backend configured');
 assert.ok(frontend.includes("textContent=text"),'user text rendered safely');
 assert.ok(frontend.includes('[data-send]'),'offline send button disabled');
 assert.ok(editor.includes('name="book"')&&editor.includes('name="page"'));
 assert.ok(!/form action="mailto:/i.test(editor),'editor correspondence never sends email');
 const share=fs.readFileSync(path.resolve(__dirname,'../public/js/ophelia-share.js'),'utf8');
 assert.ok(share.includes('function addFavoriteQuotationLink()'));
 assert.ok(share.includes('selectionFromBook()'));
 assert.ok(share.includes("url.searchParams.set('quote',passage)"));

 const emojiJS=fs.readFileSync(path.resolve(__dirname,'../public/js/ophelia-emoji.js'),'utf8');
 const emojiVM=require('node:vm');
 const emojiContext={window:{}};
 emojiVM.runInNewContext(emojiJS,emojiContext);
 const insert=emojiContext.window.OpheliaEmoji.insertedAt;
 assert.equal(insert('Jane',4,4,'🌹',2400).value,'Jane🌹','emoji appears at insertion point');
 assert.equal(insert('Hello reader',6,12,'📚',2400).value,'Hello 📚','emoji can replace selected text');
 assert.equal(insert('Hi',2,2,'😊',2),null,'emoji insert respects message length');
 assert.equal(insert('abc',1,1,'❤️',2400).caret,3,'caret advances past multi-codepoint emoji');
 assert.ok(html.includes('class="emoji-picker"'),'comment box contains emoji selection tray');
 assert.ok(html.includes('data-emoji="🌹"'),'comment emoji tray includes the Victorian rose');
 assert.ok(html.includes('ophelia-emoji.js'),'emoji tray script is loaded on public board');
 assert.ok(!editor.includes('ophelia-emoji.js'),'editor report remains a separate, private form');

 console.log('Correspondence validation and page safety checks passed.');
})().catch(e=>{console.error(e);process.exitCode=1});
